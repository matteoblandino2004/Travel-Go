/**
 * A very small ES-module bundler, for the single-file build.
 *
 * The app's modules are plain ESM with relative imports and no build step -
 * which is lovely locally and useless to a browser that has to fetch a file
 * per module. This flattens a dependency graph into one script by wrapping
 * each module in a function and resolving imports through a registry.
 *
 * It is not a general-purpose bundler and does not try to be. It handles
 * exactly the syntax this codebase uses - single-line static imports, named
 * exports, namespace imports - and throws on anything it does not recognise
 * rather than emitting something subtly wrong.
 */

import fs from 'node:fs';
import path from 'node:path';

const IMPORT_NAMED = /^import\s+\{([^}]+)\}\s+from\s+['"]([^'"]+)['"];?\s*$/;
const IMPORT_NAMESPACE = /^import\s+\*\s+as\s+(\w+)\s+from\s+['"]([^'"]+)['"];?\s*$/;
const IMPORT_DEFAULT = /^import\s+(\w+)\s+from\s+['"]([^'"]+)['"];?\s*$/;
const IMPORT_BARE = /^import\s+['"]([^'"]+)['"];?\s*$/;
const EXPORT_DECL = /^export\s+(async\s+function|function|const|let|var|class)\s+([\w$]+)/;
const EXPORT_LIST = /^export\s+\{([^}]+)\}\s*;?\s*$/;
const EXPORT_FROM = /^export\s+\{([^}]+)\}\s+from\s+['"]([^'"]+)['"];?\s*$/;
const EXPORT_DEFAULT = /^export\s+default\b/;

/**
 * @param {object} options
 * @param {string} options.root repository root
 * @param {string[]} options.entries module paths, relative to root
 * @param {Record<string,string>} [options.stubs] specifier -> replacement source
 * @returns {{code: string, modules: string[]}}
 */
export function bundle({ root, entries, stubs = {} }) {
  const modules = new Map();

  const include = (relative) => {
    const id = normalise(relative);
    if (modules.has(id)) return id;

    const absolute = path.join(root, id);
    if (!fs.existsSync(absolute)) throw new Error(`Cannot bundle missing module: ${id}`);

    const transformed = transform(fs.readFileSync(absolute, 'utf8'), id, stubs);
    modules.set(id, transformed); // register before recursing, so cycles terminate
    for (const dependency of transformed.dependencies) include(dependency);
    return id;
  };

  for (const entry of entries) include(entry);

  const registrations = [...modules.entries()]
    .map(([id, module]) => `__define(${JSON.stringify(id)}, function (exports, __require) {\n${module.code}\n});`)
    .join('\n\n');

  return {
    modules: [...modules.keys()],
    code: `${RUNTIME}\n\n${registrations}\n`,
  };
}

const RUNTIME = `// --- module runtime (generated by scripts/bundle.mjs) ---
const __registry = new Map();
const __loaded = new Map();
function __define(id, factory) { __registry.set(id, factory); }
function __require(id) {
  if (__loaded.has(id)) return __loaded.get(id);
  const factory = __registry.get(id);
  if (!factory) throw new Error('Module not bundled: ' + id);
  const exports = {};
  __loaded.set(id, exports); // set first so a cycle sees a partial object
  factory(exports, __require);
  return exports;
}`;

function transform(source, id, stubs) {
  const dependencies = new Set();
  const exported = new Set();
  const directory = path.dirname(id);

  const lines = collapseStatements(source).split('\n').map((line) => {
    const trimmed = line.trim();

    if (EXPORT_DEFAULT.test(trimmed)) {
      throw new Error(`${id}: default exports are not supported by this bundler`);
    }

    // --- imports ---
    const bare = IMPORT_BARE.exec(trimmed);
    if (bare) return '';

    const namespace = IMPORT_NAMESPACE.exec(trimmed);
    if (namespace) {
      const [, alias, specifier] = namespace;
      const resolved = resolve(specifier, directory, stubs);
      if (resolved === null) return `const ${alias} = {};`;
      dependencies.add(resolved);
      return `const ${alias} = __require(${JSON.stringify(resolved)});`;
    }

    const named = IMPORT_NAMED.exec(trimmed);
    if (named) {
      const [, bindings, specifier] = named;
      const resolved = resolve(specifier, directory, stubs);
      const destructured = bindings
        .split(',')
        .map((binding) => binding.trim())
        .filter(Boolean)
        .map((binding) => binding.replace(/\s+as\s+/, ': '))
        .join(', ');
      if (resolved === null) return `const { ${destructured} } = {};`;
      dependencies.add(resolved);
      return `const { ${destructured} } = __require(${JSON.stringify(resolved)});`;
    }

    const defaultImport = IMPORT_DEFAULT.exec(trimmed);
    if (defaultImport) {
      const [, alias, specifier] = defaultImport;
      const resolved = resolve(specifier, directory, stubs);
      if (resolved === null) return `const ${alias} = undefined;`;
      throw new Error(`${id}: default import of ${specifier} is not supported`);
    }

    // --- exports ---
    const fromList = EXPORT_FROM.exec(trimmed);
    if (fromList) {
      const [, bindings, specifier] = fromList;
      const resolved = resolve(specifier, directory, stubs);
      if (resolved === null) return '';
      dependencies.add(resolved);
      const assignments = bindings.split(',').map((b) => b.trim()).filter(Boolean).map((binding) => {
        const [name, alias = name] = binding.split(/\s+as\s+/).map((x) => x.trim());
        exported.add(alias);
        return `exports.${alias} = __require(${JSON.stringify(resolved)}).${name};`;
      });
      return assignments.join(' ');
    }

    const list = EXPORT_LIST.exec(trimmed);
    if (list) {
      for (const binding of list[1].split(',').map((b) => b.trim()).filter(Boolean)) {
        const [, alias = binding] = binding.split(/\s+as\s+/).map((x) => x.trim());
        exported.add(alias.includes(' as ') ? alias : binding.split(/\s+as\s+/).pop().trim());
      }
      return '';
    }

    // `import.meta` is a syntax error outside a module and is only ever read on
    // the Node path, which a bundled build never takes.
    if (line.includes('import.meta.url')) {
      return line.replace(/import\.meta\.url/g, "'bundled'");
    }

    const declaration = EXPORT_DECL.exec(trimmed);
    if (declaration) {
      exported.add(declaration[2]);
      return line.replace(/^(\s*)export\s+/, '$1');
    }

    // Anything still starting with import/export is syntax this bundler does
    // not understand. Failing here beats emitting a broken bundle, which is
    // what a silent pass-through produced the first time.
    if (/^(import|export)[\s{*]/.test(trimmed)) {
      throw new Error(`${id}: unsupported module syntax:\n  ${trimmed}`);
    }

    return line;
  });

  // Bind exports after the body, so hoisting and declaration order don't matter.
  const bindings = [...exported].map((name) => `exports.${name} = ${name};`).join('\n');

  return { code: `${lines.join('\n')}\n${bindings}`, dependencies: [...dependencies], exported: [...exported] };
}

/**
 * Fold an import or export spread over several lines onto one.
 *
 * The per-line transform below is much easier to read than a real parser, and
 * this is the one thing it can't see. Formatting shouldn't dictate whether a
 * module can be bundled.
 */
function collapseStatements(source) {
  return source.replace(
    /^(import|export)\s*\{([^}]*)\}\s*from\s*(['"][^'"]+['"])\s*;?/gm,
    (_, keyword, bindings, specifier) =>
      `${keyword} { ${bindings.replace(/\s+/g, ' ').trim().replace(/,$/, '')} } from ${specifier};`
  );
}

/** @returns {string|null} repo-relative module path, or null for a stubbed specifier */
function resolve(specifier, directory, stubs) {
  if (Object.hasOwn(stubs, specifier)) return null;
  if (specifier.startsWith('node:')) {
    throw new Error(`Unstubbed Node builtin "${specifier}" - add it to stubs or keep it out of the bundle`);
  }
  // The front end imports as '/src/core/flights.js', which the dev server
  // serves from the repo root; resolve those the same way.
  if (specifier.startsWith('/')) return normalise(specifier.slice(1));
  if (!specifier.startsWith('.')) throw new Error(`Cannot resolve bare specifier "${specifier}"`);
  return normalise(path.join(directory, specifier));
}

const normalise = (value) => value.split(path.sep).join('/').replace(/^\.\//, '');
